#!/usr/bin/env python3
"""Build an enabled transient SSDT and a tightly masked known-DSDT template."""
from pathlib import Path
import hashlib
import json
import struct
import subprocess
import sys

repo=Path(__file__).resolve().parents[2]
out=Path(sys.argv[1]).resolve()
out.mkdir(parents=True,exist_ok=True)
source=(repo/'Platforms/LG/timelmPkg/Experimental/UsbHost.asl').read_text()
assert source.count('Name (UHEN, Zero)')==1
asl=out/'UsbHostEnabled.asl'
asl.write_text(source.replace('Name (UHEN, Zero)','Name (UHEN, One)'),encoding='utf-8')
subprocess.run(['iasl','-ve','-p',str(out/'UsbHostEnabled'),str(asl)],check=True)
ssdt=(out/'UsbHostEnabled.aml').read_bytes()
dsdt=(repo/'Resources/DeviceOverlays/timelm/ACPI/DSDT.aml').read_bytes()
manifest=json.loads((repo/'Resources/DeviceOverlays/timelm/SHA256.json').read_text())
assert hashlib.sha256(dsdt).hexdigest()==manifest['ACPI/DSDT.aml']
for data,sig in [(ssdt,b'SSDT'),(dsdt,b'DSDT')]:
    assert data[:4]==sig and 36<=len(data)<=65536
    assert struct.unpack_from('<I',data,4)[0]==len(data) and sum(data)%256==0
assert dsdt[10:24]==b'LGE   TIMELM  ' and ssdt[16:24]==b'TIMLUSBH'

# Only data payloads written by Kona AcpiTableUpdate.c may differ. Never mask
# AML opcodes, names, package lengths, resource bytes or entire variable objects.
fields={'SOID':(0x0c,4),'STOR':(0x0c,4),'SIDV':(0x0c,4),'SVMJ':(0x0b,2),
        'SVMI':(0x0b,2),'SDFE':(0x0b,2),'SIDM':(0x0e,2),'PUS3':(0x0c,4),
        'SIDT':(0x0c,4),'SJTG':(0x0c,4),'EMUL':(0x0c,4),'SOSN':(0x0e,8),
        'PLST':(0x0c,4),'SOSI':(0x0e,8),'PRP0':(0x0c,4),'PRP1':(0x0c,4),
        'PRP2':(0x0c,4),'SIDS':(0x0d,16)}
mask=bytearray(len(dsdt)); mask[9]=1
ranges=[]
for name,(prefix,size) in fields.items():
    needle=b'\x08'+name.encode()+bytes([prefix])
    assert dsdt.count(needle)==1,name
    start=dsdt.index(needle)+len(needle)
    assert start+size<=len(dsdt)
    mask[start:start+size]=b'\x01'*size
    ranges.append({'name':name,'offset':start,'size':size})
def array(name,data):
    rows=['  '+','.join(f'0x{x:02x}' for x in data[i:i+16])+',' for i in range(0,len(data),16)]
    return 'STATIC CONST UINT8 '+name+'[]={\n'+'\n'.join(rows)+'\n};\n'
(out/'UsbWindowsAcpi.h').write_text('// Generated by generate_usb_windows_acpi.py; do not edit.\n'+
    array('mUsbHostSsdt',ssdt)+array('mTimelmDsdt',dsdt)+array('mTimelmDsdtMask',mask))
(out/'usb-windows-acpi.json').write_text(json.dumps({'ssdt_sha256':hashlib.sha256(ssdt).hexdigest(),
    'ssdt_size':len(ssdt),'dsdt_sha256':hashlib.sha256(dsdt).hexdigest(),
    'dsdt_size':len(dsdt),'enabled':True,'runtime_patches':ranges},indent=2))
